import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import ucs2lengthModule from 'ajv/dist/runtime/ucs2length.js';
import equalModule from 'ajv/dist/runtime/equal.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ajv = new Ajv({allErrors: true, strict: true, allowUnionTypes: true, inlineRefs: false,
    code: {source: true, esm: true, lines: true}, unicodeRegExp: false});
const exports = {};
for (const [name, file] of [['modelSchema', 'demo-model'], ['legacySchema', 'legacy-model'], ['catalogSchema', 'demo-catalog']]) {
    const schema = JSON.parse(await fs.readFile(path.join(root, 'schemas', file + '.schema.json'), 'utf8'));
    ajv.addSchema(schema);
    exports[name] = schema.$id;
}
const hbdsSchema = JSON.parse(await fs.readFile(path.join(root, 'HBDS/schema/configuration.schema.json'), 'utf8'));
ajv.addSchema(hbdsSchema);
// Ajv's standalone emitter uses CommonJS imports for its two runtime helpers.
// Embed those pure functions at build time so the browser needs no resolver,
// dynamic code generation, external CDN, or additional schema fetches.
const license = await fs.readFile(path.join(root, 'node_modules/ajv/LICENSE'), 'utf8');
for (const [filename, names] of [
    ['openbexi_timeline_schema_validators.js', exports],
    ['openbexi_timeline_hbds_validator.js', {hbdsSchema: hbdsSchema.$id}]
]) {
let generated = standaloneCode(ajv, names);
for (const [name, module] of [['ucs2length', ucs2lengthModule], ['equal', equalModule]]) {
    generated = generated.replaceAll(`require("ajv/dist/runtime/${name}").default`, (module.default || module).toString());
}
if (/\brequire\s*\(/.test(generated)) throw new Error('Unexpected runtime import in generated browser validators.');
const code = '// Generated by npm run demos:schemas. Edit schemas/*.schema.json, then regenerate.\n' +
    '/* Ajv generated validation and runtime helpers:\n' + license.trim() + '\n*/\n' + generated;
const target = path.join(root, 'src', filename);
if (process.argv.includes('--check')) {
    if ((await fs.readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== code) throw new Error('Compiled demo validators are stale. Run npm run demos:schemas.');
} else {
    await fs.writeFile(target, code);
    console.log('Compiled ' + filename + '.');
}
}
